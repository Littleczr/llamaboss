// tool_notes.h
//
// User notes -- a folder of small markdown files (cross-conversation
// memory), browsed like a file tree instead of read as one big log.
//
//   %USERPROFILE%\LlamaBoss\Notes\
//     paths.md                 <- default target for short facts
//     preferences.md
//     mac-mini\setup-log.md    <- one subject per file, <= 1 subfolder deep
//     projects\<name>.md
//
// How the model sees it:
//   * BuildNotesIndexBlock() renders a compact index (one line per file:
//     relative path + description) that ProjectContextBuilder injects into
//     the system prompt.  Descriptions come from each file's YAML
//     frontmatter `description:` line (same convention as SKILL.md), or
//     the first content line when a file has no frontmatter.  The index
//     is generated by LlamaBoss -- the model never has to maintain it.
//   * File CONTENTS are never injected.  The model opens a file with the
//     normal read tool only when the task needs it.
//   * notes_append is the one notes-specific tool: it appends one short
//     fact (<= 300 characters, <= 3 lines) as a bullet to paths.md, or to
//     another EXISTING notes file named on a first `file: <name>.md` line.
//     Longer material is refused with guidance to create a subject file.
//   * Creating or editing notes files uses the normal write/edit tools.
//     The Notes folder is not a default write root, so the first such
//     change in a chat shows the existing "Folder Access Required" card
//     (granting the whole Notes folder via ToolContext::notesRoot).
//
// The pre-folder %USERPROFILE%\LlamaBoss\NOTES.md is left untouched.  While
// it exists, the index mentions it as a legacy file so nothing saved before
// the migration is lost to the model.
//
// Threading: synchronous on the caller's thread; files are small.
//
#pragma once

#include "tool_context.h"

#include <cstdint>
#include <string>
#include <vector>

// Result type -- mirrors the chip / body / errorBody shape used by every
// other sync tool so the dispatcher can pack it into a ToolBlock.
struct NotesResult {
    std::vector<std::string> chips;
    std::string              body;
    std::string              errorBody;
    std::string              bodyLang;     // "markdown" on success
};

// One indexed notes file.  Field names match what
// ProjectContextBuilder's FingerprintItems() expects (name/path/sizeBytes).
struct NoteFileInfo {
    std::string   name;        // path relative to the Notes folder ("mac-mini\\setup-log.md")
    std::string   path;        // absolute path
    std::uint64_t sizeBytes = 0;
};

// %USERPROFILE%\LlamaBoss (fallbacks: ~/LlamaBoss, <Documents>\LlamaBoss).
// Shared with reminder_store.h, which keeps REMINDERS.json here.
std::string GetLlamaBossUserRootDir();

// <user root>\Notes.  Not created by this call.
std::string GetNotesRootDir();

// <user root>\NOTES.md -- the pre-folder single-file notes.  Read-only
// legacy; nothing writes it any more.
std::string GetLegacyNotesPath();

// Lists *.md files in the Notes folder root and one subfolder level,
// sorted by relative path (root files first).  Hidden files and other
// extensions are skipped.  Missing folder -> empty list.
std::vector<NoteFileInfo> ListNoteFiles();

// The "User notes" system-prompt section: folder path, per-file index,
// and the legacy NOTES.md pointer when that file still exists.  Bounded
// in size; falls back to per-folder counts when the full index is large.
std::string BuildNotesIndexBlock();

// Static notes guidance for the agent prompts (both protocols).  Byte-
// stable so it does not disturb prompt caching.
const char* NotesAgentPromptGuidance();

// notes_append.  `args` is the entry text, optionally preceded by a first
// line `file: <relative>.md` naming an existing notes file.
NotesResult NotesAppend(const std::string& args, const ToolContext& ctx);
